// Merges the researched recipe JSON files into src/data/recipes.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const filipino = JSON.parse(readFileSync(join(here, 'filipino.json'), 'utf8'));
const vietnamese = JSON.parse(readFileSync(join(here, 'vietnamese.json'), 'utf8'));
const thai = JSON.parse(readFileSync(join(here, 'thai.json'), 'utf8'));
const spanish = JSON.parse(readFileSync(join(here, 'spanish.json'), 'utf8'));

const all = [...filipino, ...vietnamese, ...thai, ...spanish];

// basic validation
const slugs = new Set();
for (const r of all) {
  for (const key of ['slug', 'name', 'cuisine', 'category', 'description', 'sourceName', 'sourceUrl', 'difficulty']) {
    if (!r[key]) throw new Error(`Missing ${key} in ${r.slug || JSON.stringify(r).slice(0, 60)}`);
  }
  if (slugs.has(r.slug)) throw new Error(`Duplicate slug: ${r.slug}`);
  slugs.add(r.slug);
  if (!Array.isArray(r.ingredients) || r.ingredients.length === 0) {
    throw new Error(`No ingredients for ${r.slug}`);
  }
  // normalize: quantity null -> '' ; strip stray HTML entities
  r.ingredients = r.ingredients.map((i) => ({
    group: i.group ? String(i.group).replaceAll('&amp;', '&') : null,
    quantity: i.quantity ? String(i.quantity).replaceAll('&amp;', '&') : '',
    item: String(i.item).replaceAll('&amp;', '&'),
  }));
}

const header = `// Auto-generated by scripts/generate-recipes.mjs — do not edit by hand.
// Sources: see sourceUrl on each recipe. Ingredient lists mirror the original
// recipe pages so they can be used directly as shopping lists.
import type { Recipe } from '../types';

export const RECIPES: Recipe[] = `;

writeFileSync(
  join(here, '..', 'src', 'data', 'recipes.ts'),
  header + JSON.stringify(all, null, 2) + ';\n',
);

console.log(
  `Wrote ${all.length} recipes (${filipino.length} Filipino, ${vietnamese.length} Vietnamese, ${thai.length} Thai, ${spanish.length} Spanish)`,
);
